// @title Anubis — сервис авторизации
// @version local
// @description Сервер авторизации (OAuth2, токены, проекты) с конфигурацией по доменам.
// @BasePath /
//
// @schemes https http
//
// @accept json
// @produce json
//
// @tag.name Auth
// @tag.description Авторизация, OAuth2, токены
// @tag.name Workspace
// @tag.description Проекты и участники проектов
// @tag.name Health
// @tag.description Проверки здоровья сервиса
//
// @securityDefinitions.apikey BearerAuth
// @in header
// @name Authorization
// @description Формат: "Bearer <access_token>"
//
// Точка входа сервиса авторизации.
func main() {
	var config core.ServiceConfig
	config.ReadConfig("config_server.yaml")
	if err := config.Validate(); err != nil {
		log.Fatalf("CONFIG ERROR: %v", err)
	}

	// ---------- 2. Инициализируем логгер ----------

	// InitLogger настраивает глобальный ZapLogger в пакете common.
	common.InitLogger(config.App.Mode)
	defer func(ZapLogger *zap.Logger) {
		// Sync сбрасывает буферы логгера на диск/stdout.
		// IMPORTANT: в некоторых окружениях (Docker/CI) Sync() на stdout/stderr может вернуть EINVAL/ENOTTY.
		// Это известный кейс, его нельзя считать критическим (см. практику zap).
		if err := ZapLogger.Sync(); err != nil {
			if errors.Is(err, syscall.EINVAL) || errors.Is(err, syscall.ENOTTY) {
				return
			}
			log.Printf("WARN: zap logger sync failed: %v\n", err)
		}
	}(common.ZapLogger)

	common.ZapLogger.Info(
		"starting auth service",
		zap.String("version", config.App.Version),
		zap.String("ip", config.App.IP),
		zap.String("URL", config.App.URL),
		zap.String("Mode", config.App.Mode),
	)

	// ---------- 3. Настраиваем кастомные валидаторы ----------

	if v, ok := binding.Validator.Engine().(*validator.Validate); ok {
		// Валидация телефона (твой кастомный тег "phone")
		if err := v.RegisterValidation("phone", common.ValidatePhone); err != nil {
			log.Fatalf("CRITICAL: validate error (phone): %v", err)
		}
		// Валидация безопасного текста (запрет <>&\ “ ')
		if err := v.RegisterValidation("safe_text", common.ValidateSafeText); err != nil {
			log.Fatalf("CRITICAL: validate error (safe_text): %v", err)
		}
		// Валидация ObjectID (mongo-style id)
		if err := v.RegisterValidation("object_id", common.ValidateObjectId); err != nil {
			log.Fatalf("CRITICAL: validate error (object_id): %v", err)
		}
	}

	// ---------- 4. Контекст приложения + graceful shutdown ----------

	// ctx отменится, когда мы получим SIGINT/SIGTERM (Ctrl+C, docker stop и т.п.)
	ctx, stop := signal.NotifyContext(context.Background(), syscall.SIGINT, syscall.SIGTERM)
	defer stop()

	// ---------- 5. Подключаемся к Postgres (если включен) ----------

	var pgPool *pgxpool.Pool

	// Формируем DSN вида:
	// storage://user:password@host:port/database?sslmode=disable
	dsn := fmt.Sprintf(
		"postgres://%s:%s@%s:%d/%s?sslmode=%s",
		config.Postgres.User,
		url.QueryEscape(config.Postgres.Password),
		config.Postgres.Host,
		config.Postgres.Port,
		config.Postgres.Database,
		config.Postgres.SSLMode,
	)

	// NewClientPgx — твой helper из tools/dtb/psql/pgxpool.go
	// timeoutConnect = 5 секунд, попыток = 5, размер пула — из конфига.
	var err error
	pgPool, err = dtb.NewClientPgx(ctx, 5, 5*time.Second, dsn, int(config.Postgres.MaxPool))
	if err != nil {
		log.Fatalf("CRITICAL: failed to connect to PostgreSQL: %v\n", err)
	}
	defer dtb.ClosePostgresConnection(pgPool)

	common.ZapLogger.Info("storage connected",
		zap.String("host", config.Postgres.Host),
		zap.Int("port", config.Postgres.Port),
		zap.String("db", config.Postgres.Database),
	)

	// ---------- 6. Создаём Gin-приложение ----------

	app := gin.New()

	// Recovery — чтобы паника в хендлере не уронила весь процесс.
	app.Use(gin.Recovery())

	// Обработчик "нет такого маршрута" — чтобы отдавать JSON 404.
	app.NoRoute(func(c *gin.Context) {
		c.JSON(http.StatusNotFound, gin.H{"error": "not found"})
	})

	// Gzip сжимает ответы (экономим трафик).
	app.Use(gzip.Gzip(gzip.BestCompression))

	// Логгер запросов — твой кастомный middleware.
	app.Use(middlewares.RequestLoggerMiddleware(common.ZapLogger))

	// В зависимости от окружения — режим Gin.
	if config.App.Mode != "development" {
		gin.SetMode(gin.ReleaseMode)
	} else {
		gin.SetMode(gin.DebugMode)

		// Отдельный маршрут, чтобы руками вызвать панику и проверить Recovery/логирование.
		app.GET("/panic_route", func(c *gin.Context) {
			panic("This is a simulated panic!")
		})
	}

	// ---------- 7. CORS ----------

	// В dev можно разрешать всё, в prod — ограничиваем по доменам (trusted_host_suffixes).
	corsCfg := cors.Config{
		AllowMethods: []string{"GET", "POST", "DELETE", "PATCH", "PUT", "OPTIONS"},
		AllowHeaders: []string{"Content-Type", "Authorization", "Accept-Encoding"},
		ExposeHeaders: []string{
			"X-Request-ID",
		},
		MaxAge: 12 * time.Hour,
	}

	if config.App.Mode == "development" {
		corsCfg.AllowAllOrigins = true
	} else {
		corsCfg.AllowCredentials = true
		corsCfg.AllowOriginFunc = func(origin string) bool {
			origin = strings.TrimSpace(origin)
			if origin == "" {
				return false
			}
			u, err := url.Parse(origin)
			if err != nil {
				return false
			}
			host := u.Hostname()
			return isTrustedHostSuffix(host, config.App.TrustedHostSuffixes)
		}
	}

	app.Use(cors.New(corsCfg))

	// ---------- 8. Тестовый публичный маршрут ----------

	// Swagger UI (generated docs).
	if config.App.Mode == "development" {
		app.GET("/swagger", func(c *gin.Context) {
			c.Redirect(http.StatusFound, "/swagger/index.html")
		})
		app.GET("/swagger/*any", ginSwagger.WrapHandler(swaggerFiles.Handler))
	}

	app.GET("/ping", routes.PingHandler(config.App.Version))

	// ---------- 9. Middleware доменов/сервисов ----------

	// DomainMiddleware, судя по названию, достаёт из хедеров/host информацию о сервисе
	// (chanki/yocha/...), и проверяет, что этот домен описан в config.ListServices.
	app.Use(middlewares.DomainMiddleware(config))

	// ---------- 10. Здесь будут все реальные роуты авторизации ----------

	// Пример для будущих роутов:
	//
	authGroup := app.Group("/auth")

	routes.NewRouteOAuth2AuthPg(pgPool, authGroup, config)
	routes.NewRouteToken(pgPool, authGroup, config)
	routes.NewRouteTelegramAuth(pgPool, authGroup, config)
	workspaceGroup := app.Group("/workspace")
	routes.NewRouteWorkspace(pgPool, workspaceGroup, config)
	routes.NewRouteRoles(pgPool, app, config)
	// ---------- 11. Пример защищённого маршрута с JWT ----------

	protectedRouter := app.Group("/ping_auth")
	protectedRouter.Use(middlewares.JwtAuthMiddleware(config))
	protectedRouter.GET("", routes.PingAuthHandler(config.App.Version))

	// ---------- 12. Запускаем HTTP-сервер с graceful shutdown ----------

	server := &http.Server{
		Addr:    config.App.IP, // пример: 0.0.0.0:1012
		Handler: app,

		// IMPORTANT (security / reliability):
		// Эти таймауты защищают от "slowloris" и не дают зависать коннектам бесконечно.
		// Значения можно позже вынести в конфиг, но даже дефолты лучше, чем их отсутствие.
		ReadHeaderTimeout: 5 * time.Second,
		ReadTimeout:       15 * time.Second,
		WriteTimeout:      30 * time.Second,
		IdleTimeout:       60 * time.Second,
		MaxHeaderBytes:    1 << 20, // 1 MiB
	}

	// Запускаем сервер в отдельной горутине.
	go func() {
		common.ZapLogger.Info("http server is starting", zap.String("addr", config.App.IP))
		if err := server.ListenAndServe(); err != nil && err != http.ErrServerClosed {
			common.ZapLogger.Fatal("unexpected error while starting server", zap.Error(err))
		}
	}()

	// Ждём сигнала остановки (Ctrl+C / docker stop).
	<-ctx.Done()
	common.ZapLogger.Info("shutdown signal received")

	// Новый контекст с таймаутом для корректного завершения активных запросов.
	shutdownCtx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()

	if err := server.Shutdown(shutdownCtx); err != nil {
		common.ZapLogger.Error("server forced to shutdown", zap.Error(err))
	} else {
		common.ZapLogger.Info("server exited gracefully")
	}

	// Если нужно, можно тут же подчистить какие-то фоновые задачи,
	// очереди, воркеры и т.п.
	_ = os.Stdout // чтобы импорт os не ругался, если его не используем дальше
}

func isTrustedHostSuffix(host string, suffixes []string) bool {
	host = strings.TrimSuffix(strings.ToLower(strings.TrimSpace(host)), ".")
	if host == "" {
		return false
	}
	for _, s := range suffixes {
		s = strings.TrimSuffix(strings.ToLower(strings.TrimSpace(s)), ".")
		if s == "" {
			continue
		}
		if host == s || strings.HasSuffix(host, "."+s) {
			return true
		}
	}
	return false
}
